"""Summarize Ghidra evidence without publishing any Sony instructions."""
from pathlib import Path
import collections, hashlib, json, re

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT/'local_only'/'analysis'
OUT = BASE/'p0d'
names = {0:'allocate_memory',1:'write_htab_entry',2:'construct_virtual_address_space',
  7:'select_virtual_address_space',9:'pause',15:'put_iopte',18:'construct_event_receive_port',
  24:'destruct_event_receive_port',27:'end_of_interrupt',28:'connect_irq_plug',
  57:'allocate_io_segment',61:'release_io_segment',91:'read_repository_node',
  162:'read_virtual_uart',163:'write_virtual_uart',164:'set_virtual_uart_param',
  165:'get_virtual_uart_param',166:'configure_virtual_uart_irq',170:'open_device',171:'close_device',
  172:'map_device_mmio_region',173:'unmap_device_mmio_region',174:'allocate_device_dma_region',
  175:'free_device_dma_region',176:'map_device_dma_region',177:'unmap_device_dma_region',
  197:'connect_interrupt_event_receive_port',245:'storage_read',246:'storage_write',
  248:'storage_send_device_command',249:'storage_get_async_status',254:'storage_check_async_status',255:'panic'}
source = (ROOT/'local_only'/'research'/'lv1call_web.txt').read_text(encoding='utf-8')
names.update({int(n):name for name,n in re.findall(r'LV1_CALL\((\w+),\s*\d+,\s*\d+,\s*(\d+)\s*\)',source)})
# Linux mappings absent from the table remain numeric, rather than guessed.
def inventory(path):
    rows = json.loads(path.read_text())
    return rows, [r for r in rows if r['hypercall'] is not None and
                 (r.get('lev') == 1 or r.get('forwarded') or 'lev=1' in r.get('scan',''))]

all_rows = {'netemu':inventory(BASE/'sc_inventory.json')}
for variant in ['ps2_emu','ps2_gxemu']:
    all_rows[variant] = inventory(OUT/variant/'sc_inventory.json')
sets = {k:set(r['hypercall'] for r in pair[1]) for k,pair in all_rows.items()}
summary = {}
lines = ['<!-- Generated by tools/p0d_inventory.py; static interpretations are INFERRED. -->',
         '### Full constant-number comparison', '',
         '**INFERRED:** site counts include decoded candidates, not runtime executions; data templates may occur. Unknown public names are left numeric. Wrapper caller counts below are direct call-instruction lower bounds.', '',
         '| LV1 number / name | stock netemu sites | ps2_emu sites | ps2_gxemu sites |',
         '| --- | ---: | ---: | ---: |']
for n in sorted(set.union(*sets.values())):
    counts = [sum(r['hypercall']==n for r in all_rows[k][1]) for k in all_rows]
    lines.append(f'| {n} / `0x{n:x}` {names.get(n,"UNKNOWN name")} | '+ ' | '.join(map(str,counts))+' |')
for k,(rows, classified) in all_rows.items():
    summary[k] = {'sc_words':len(rows),'lev1':sum(r.get('lev')==1 or 'lev=1' in r.get('scan','') for r in rows),
                  'forwarded':sum(r['forwarded'] for r in rows),'constant_sites':len(classified),
                  'numbers':sorted(sets[k]),'extra_vs_netemu':sorted(sets[k]-sets['netemu'])}
    if k=='netemu': continue
    lines += ['',f'### {k}: wrappers and callers','',
              '**INFERRED:** grouped by Ghidra function and constant LV1 number. An unassigned site is retained. `calls` excludes data/function-descriptor references; indirect callers remain UNKNOWN.', '',
              '| LV1 | Wrapper | Direct calls | Sites |','| --- | --- | ---: | --- |']
    groups=collections.defaultdict(list)
    for row in classified: groups[(row['hypercall'],row['function'])].append(row)
    for (n,f), group in sorted(groups.items(),key=lambda x:(x[0][0],x[0][1] or '')):
        calls={r['from'] for g in group for r in g['references'] if 'CALL' in r['type']}
        sites=', '.join(g['site'] for g in group)
        lines.append(f'| {n} / `0x{n:x}` | {"0x"+f if f else "unassigned"} | {len(calls)} | {sites} |')
(OUT/'inventory_tables.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
(OUT/'inventory_summary.json').write_text(json.dumps(summary,indent=2))
print(json.dumps(summary,indent=2))
